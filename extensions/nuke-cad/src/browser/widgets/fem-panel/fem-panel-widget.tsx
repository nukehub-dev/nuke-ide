/**
 * FEM analysis panel widget.
 *
 * Configures materials and boundary conditions for a mesh generated by the
 * nuke-cad meshing service, writes a CalculiX input deck, runs ccx, and
 * converts the FRD result to VTK for visualization in nuke-visualizer.
 *
 * @module nuke-cad/browser/widgets
 */

import * as React from '@theia/core/shared/react';
import { injectable, inject, postConstruct } from '@theia/core/shared/inversify';
import { ReactWidget } from '@theia/core/lib/browser/widgets/react-widget';
import { MessageService } from '@theia/core/lib/common/message-service';
import { OpenerService } from '@theia/core/lib/browser/opener-service';
import { URI } from '@theia/core/lib/common/uri';

import {
    NukeCadBackendService,
    FemRunRequest,
    FemRunResult,
    FemMaterial,
    FemBoundaryCondition,
    FemStepSettings
} from '../../../common/nuke-cad-protocol';
import { NukeCadStateManager } from '../../state/nuke-cad-state-manager';
import { NukeSelect } from 'nuke-essentials/lib/theme/browser/components';
import './fem-panel.css';

interface FemPanelState {
    analysisType: 'static' | 'heatTransfer' | 'frequency';
    materials: Record<string, string>;
    boundaryConditions: FemBoundaryCondition[];
    stepTime: number;
    gravityEnabled: boolean;
    gravityMagnitude: number;
    gravityVector: [number, number, number];
    isRunning: boolean;
    logOutput: string;
    lastResult?: FemRunResult;
    builtInMaterials: FemMaterial[];
}

@injectable()
export class FemPanelWidget extends ReactWidget {
    static readonly ID = 'nuke-cad-fem-panel-widget';
    static readonly LABEL = 'FEM Analysis';

    @inject(MessageService)
    protected readonly messageService: MessageService;

    @inject(NukeCadStateManager)
    protected readonly stateManager: NukeCadStateManager;

    @inject(NukeCadBackendService)
    protected readonly backendService: NukeCadBackendService;

    @inject(OpenerService)
    protected readonly openerService: OpenerService;

    private state: FemPanelState = {
        analysisType: 'static',
        materials: {},
        boundaryConditions: [],
        stepTime: 1,
        gravityEnabled: false,
        gravityMagnitude: 9.81,
        gravityVector: [0, 0, -1],
        isRunning: false,
        logOutput: '',
        builtInMaterials: []
    };

    /** Job id of the in-flight FEM run, cancellable via the backend. */
    private currentJobId?: string;

    @postConstruct()
    protected init(): void {
        this.id = FemPanelWidget.ID;
        this.title.label = FemPanelWidget.LABEL;
        this.title.closable = true;
        this.title.iconClass = 'codicon codicon-dashboard';

        this.loadMaterials();
        this.toDispose.push(
            this.stateManager.onModelChange(() => {
                this.resetForModel();
                this.update();
            })
        );
        this.update();
    }

    private async loadMaterials(): Promise<void> {
        try {
            const materials = await this.backendService.listFemMaterials();
            this.state.builtInMaterials = materials;
            this.update();
        } catch {
            // Built-in list is non-critical; the UI will show empty.
        }
    }

    private resetForModel(): void {
        const report = this.stateManager.model?.result.meshReport;
        const blocks = report?.blocks ?? [];
        const materials: Record<string, string> = {};
        for (const block of blocks) {
            materials[block.name] = 'structural_steel';
        }
        this.state = {
            ...this.state,
            materials,
            boundaryConditions: [],
            lastResult: undefined,
            logOutput: ''
        };
    }

    private get surfaceNames(): string[] {
        const manifestSurfaces = this.stateManager.model?.manifest?.surfaces.map((s) => s.name ?? s.selector) ?? [];
        const reportSidesets = this.stateManager.model?.result.meshReport?.sidesets?.map((s) => s.name) ?? [];
        return Array.from(new Set([...manifestSurfaces, ...reportSidesets]));
    }

    private get blockNames(): string[] {
        return this.stateManager.model?.result.meshReport?.blocks.map((b) => b.name) ?? [];
    }

    private get mshPath(): string | undefined {
        return this.stateManager.model?.result.meshPath;
    }

    private async runAnalysis(): Promise<void> {
        const mshPath = this.mshPath;
        if (!mshPath) {
            this.messageService.warn('No mesh is available. Build or import a CAD model first.');
            return;
        }

        const materials: Record<string, string | FemMaterial> = {};
        for (const block of this.blockNames) {
            const key = this.state.materials[block] ?? 'structural_steel';
            const builtIn = this.state.builtInMaterials.find(
                (m) => key.toLowerCase().replace(/\s+/g, '_') === m.name.toLowerCase().replace(/\s+/g, '_')
            );
            materials[block] = builtIn ?? key;
        }

        let step: FemStepSettings = {
            stepType: this.state.analysisType,
            time: this.state.stepTime,
            initialTimeIncrement: this.state.stepTime
        };
        if (this.state.gravityEnabled && this.state.analysisType !== 'heatTransfer') {
            step = {
                ...step,
                gravity: {
                    magnitude: this.state.gravityMagnitude,
                    vector: Array.from(this.state.gravityVector)
                }
            };
        }

        const jobId = `fem-${Date.now()}`;
        const request: FemRunRequest = {
            mshPath,
            materials,
            boundaryConditions: this.state.boundaryConditions,
            step,
            run: true,
            jobId
        };

        this.currentJobId = jobId;
        this.state.isRunning = true;
        this.state.logOutput = 'Running FEM setup...\n';
        this.update();

        try {
            const result = await this.backendService.runFem(request);
            this.state.lastResult = result;
            this.state.logOutput = [result.stdout, result.stderr].filter(Boolean).join('\n');
            if (result.success) {
                this.messageService.info(`FEM analysis complete: ${result.vtkPath ? 'VTK written' : 'input deck written'}`);
            } else if (result.error === 'Job cancelled.') {
                this.state.logOutput += '\nFEM analysis cancelled.';
                this.messageService.info('FEM analysis cancelled.');
            } else {
                this.messageService.error(result.error || 'FEM analysis failed.');
            }
        } catch (error) {
            const msg = error instanceof Error ? error.message : String(error);
            this.state.logOutput += `\nError: ${msg}`;
            this.messageService.error(msg);
        } finally {
            this.currentJobId = undefined;
            this.state.isRunning = false;
            this.update();
        }
    }

    private async stopAnalysis(): Promise<void> {
        const jobId = this.currentJobId;
        if (!jobId) {
            return;
        }
        try {
            const cancelled = await this.backendService.cancelJob(jobId);
            if (!cancelled) {
                this.messageService.warn('The FEM job is no longer running.');
            }
        } catch (error) {
            this.messageService.error(error instanceof Error ? error.message : String(error));
        }
    }

    private addBoundaryCondition(bc: FemBoundaryCondition): void {
        this.state.boundaryConditions = [...this.state.boundaryConditions, bc];
        this.update();
    }

    private removeBoundaryCondition(id: string): void {
        this.state.boundaryConditions = this.state.boundaryConditions.filter((bc) => bc.id !== id);
        this.update();
    }

    private async openResult(): Promise<void> {
        const vtkPath = this.state.lastResult?.vtkPath;
        if (!vtkPath) {
            this.messageService.warn('No VTK result is available.');
            return;
        }
        try {
            const opener = await this.openerService.getOpener(new URI(vtkPath));
            await opener.open(new URI(vtkPath));
        } catch (error) {
            const msg = error instanceof Error ? error.message : String(error);
            this.messageService.error(`Could not open result: ${msg}`);
        }
    }

    protected render(): React.ReactNode {
        return (
            <FemPanelComponent
                state={this.state}
                surfaces={this.surfaceNames}
                blocks={this.blockNames}
                mshPath={this.mshPath}
                onAnalysisTypeChange={(t) => {
                    this.state.analysisType = t;
                    this.update();
                }}
                onMaterialChange={(block, material) => {
                    this.state.materials = { ...this.state.materials, [block]: material };
                    this.update();
                }}
                onStepTimeChange={(v) => {
                    this.state.stepTime = v;
                    this.update();
                }}
                onGravityToggle={(enabled) => {
                    this.state.gravityEnabled = enabled;
                    this.update();
                }}
                onGravityMagnitudeChange={(v) => {
                    this.state.gravityMagnitude = v;
                    this.update();
                }}
                onGravityVectorChange={(v) => {
                    this.state.gravityVector = v;
                    this.update();
                }}
                onAddBc={(bc) => this.addBoundaryCondition(bc)}
                onRemoveBc={(id) => this.removeBoundaryCondition(id)}
                onRun={() => this.runAnalysis()}
                onStop={() => this.stopAnalysis()}
                onOpenResult={() => this.openResult()}
            />
        );
    }
}

interface FemPanelComponentProps {
    readonly state: FemPanelState;
    readonly surfaces: string[];
    readonly blocks: string[];
    readonly mshPath: string | undefined;
    readonly onAnalysisTypeChange: (type: 'static' | 'heatTransfer' | 'frequency') => void;
    readonly onMaterialChange: (block: string, material: string) => void;
    readonly onStepTimeChange: (value: number) => void;
    readonly onGravityToggle: (enabled: boolean) => void;
    readonly onGravityMagnitudeChange: (value: number) => void;
    readonly onGravityVectorChange: (value: [number, number, number]) => void;
    readonly onAddBc: (bc: FemBoundaryCondition) => void;
    readonly onRemoveBc: (id: string) => void;
    readonly onRun: () => void;
    readonly onStop: () => void;
    readonly onOpenResult: () => void;
}

function FemPanelComponent(props: FemPanelComponentProps): React.ReactElement {
    const [newBcType, setNewBcType] = React.useState<FemBoundaryCondition['type']>('fixed');
    const [newBcSurface, setNewBcSurface] = React.useState('');
    const [newBcMagnitude, setNewBcMagnitude] = React.useState(0);
    const [newBcTemperature, setNewBcTemperature] = React.useState(300);
    const [newBcPressureVector, setNewBcPressureVector] = React.useState<[number, number, number]>([0, 0, 1]);
    const [newBcDisplacementVector, setNewBcDisplacementVector] = React.useState<[number, number, number]>([0, 0, 1]);

    const materialOptions = props.state.builtInMaterials.map((m) => m.name);
    const canRun = props.mshPath !== undefined && !props.state.isRunning;

    const handleAddBc = (): void => {
        if (!newBcSurface) {
            return;
        }
        const needsMagnitude = newBcType === 'pressure' || newBcType === 'heatFlux' || newBcType === 'displacement';
        const bc: FemBoundaryCondition = {
            id: `bc-${Date.now()}`,
            type: newBcType,
            surfaceName: newBcSurface,
            ...(newBcType === 'temperature' ? { temperature: newBcTemperature } : {}),
            ...(needsMagnitude ? { magnitude: newBcMagnitude } : {}),
            ...(newBcType === 'pressure' ? { vector: Array.from(newBcPressureVector) } : {}),
            ...(newBcType === 'displacement' ? { vector: Array.from(newBcDisplacementVector) } : {})
        };
        props.onAddBc(bc);
    };

    return (
        <div className="fem-panel-widget">
            <div className="fem-panel-header">
                <div className="header-info">
                    <h2>
                        <i className="codicon codicon-dashboard" />
                        FEM Analysis
                    </h2>
                    <p className="header-description">Set up and run CalculiX structural or thermal simulations</p>
                </div>
                <div className="header-actions">
                    <button className="theia-button primary" onClick={props.onRun} disabled={!canRun}>
                        <i className="codicon codicon-play" />
                        {props.state.isRunning ? 'Running...' : 'Run FEM'}
                    </button>
                    {props.state.isRunning && (
                        <button className="theia-button secondary" onClick={props.onStop}>
                            <i className="codicon codicon-stop" />
                            Stop
                        </button>
                    )}
                    {props.state.lastResult?.vtkPath && (
                        <button className="theia-button secondary" onClick={props.onOpenResult}>
                            <i className="codicon codicon-open-preview" />
                            Open VTK Result
                        </button>
                    )}
                </div>
            </div>

            <div className="fem-panel-content">
                {!props.mshPath && (
                    <div className="fem-panel-placeholder">Open a CAD model and build a mesh to configure a FEM analysis.</div>
                )}

                <div className="fem-section">
                    <div className="fem-section-title">Analysis Type</div>
                    <div className="form-row">
                        <div className="form-group">
                            <NukeSelect
                                ariaLabel="Analysis type"
                                value={props.state.analysisType}
                                options={[
                                    { value: 'static', label: 'Static Structural' },
                                    { value: 'heatTransfer', label: 'Steady-State Thermal' },
                                    { value: 'frequency', label: 'Frequency' }
                                ]}
                                onChange={(value) => props.onAnalysisTypeChange(value as 'static' | 'heatTransfer' | 'frequency')}
                            />
                        </div>
                        <div className="form-group">
                            <label>Step Time</label>
                            <input
                                type="number"
                                step="any"
                                min={0.001}
                                value={props.state.stepTime}
                                onChange={(e) => props.onStepTimeChange(parseFloat(e.target.value) || 1)}
                            />
                        </div>
                    </div>
                </div>

                {props.state.analysisType !== 'heatTransfer' && (
                    <div className="fem-section">
                        <div className="fem-section-title">Gravity Load</div>
                        <div className="form-row">
                            <div className="form-group inline">
                                <input
                                    type="checkbox"
                                    checked={props.state.gravityEnabled}
                                    onChange={(e) => props.onGravityToggle(e.target.checked)}
                                />
                                <label>Enable gravity</label>
                            </div>
                            <div className="form-group">
                                <label>Magnitude</label>
                                <input
                                    type="number"
                                    step="any"
                                    value={props.state.gravityMagnitude}
                                    disabled={!props.state.gravityEnabled}
                                    onChange={(e) => props.onGravityMagnitudeChange(parseFloat(e.target.value) || 0)}
                                />
                            </div>
                        </div>
                        <VectorInput
                            label="Direction"
                            value={props.state.gravityVector}
                            disabled={!props.state.gravityEnabled}
                            onChange={props.onGravityVectorChange}
                        />
                    </div>
                )}

                <div className="fem-section">
                    <div className="fem-section-title">Materials</div>
                    {props.blocks.length === 0 && <div className="fem-hint">No mesh blocks available.</div>}
                    {props.blocks.map((block) => (
                        <div className="form-row" key={block}>
                            <div className="form-group">
                                <label>{block}</label>
                                <NukeSelect
                                    ariaLabel={block}
                                    value={props.state.materials[block] ?? 'structural_steel'}
                                    options={materialOptions.map((name) => ({
                                        value: name.toLowerCase().replace(/\s+/g, '_'),
                                        label: name
                                    }))}
                                    onChange={(value) => props.onMaterialChange(block, value)}
                                />
                            </div>
                        </div>
                    ))}
                </div>

                <div className="fem-section">
                    <div className="fem-section-title">Boundary Conditions</div>
                    <div className="form-row">
                        <div className="form-group">
                            <label>Type</label>
                            <NukeSelect
                                ariaLabel="Type"
                                value={newBcType}
                                options={[
                                    { value: 'fixed', label: 'Fixed (ENCASTRE)' },
                                    { value: 'displacement', label: 'Displacement' },
                                    { value: 'pressure', label: 'Pressure' },
                                    { value: 'temperature', label: 'Temperature' },
                                    { value: 'heatFlux', label: 'Heat Flux' }
                                ]}
                                onChange={(value) => setNewBcType(value as FemBoundaryCondition['type'])}
                            />
                        </div>
                        <div className="form-group">
                            <label>Surface</label>
                            <NukeSelect
                                ariaLabel="Surface"
                                value={newBcSurface}
                                options={[
                                    { value: '', label: 'Select surface...' },
                                    ...props.surfaces.map((s) => ({ value: s, label: s }))
                                ]}
                                onChange={(value) => setNewBcSurface(value)}
                            />
                        </div>
                        {newBcType === 'temperature' ? (
                            <div className="form-group">
                                <label>Temperature (K)</label>
                                <input
                                    type="number"
                                    step="any"
                                    value={newBcTemperature}
                                    onChange={(e) => setNewBcTemperature(parseFloat(e.target.value) || 0)}
                                />
                            </div>
                        ) : (
                            <div className="form-group">
                                <label>Magnitude</label>
                                <input
                                    type="number"
                                    step="any"
                                    value={newBcMagnitude}
                                    onChange={(e) => setNewBcMagnitude(parseFloat(e.target.value) || 0)}
                                />
                            </div>
                        )}
                    </div>
                    {newBcType === 'pressure' && (
                        <VectorInput
                            label="Pressure Direction"
                            value={newBcPressureVector}
                            disabled={false}
                            onChange={setNewBcPressureVector}
                        />
                    )}
                    {newBcType === 'displacement' && (
                        <VectorInput
                            label="Displacement Direction"
                            value={newBcDisplacementVector}
                            disabled={false}
                            onChange={setNewBcDisplacementVector}
                        />
                    )}
                    <button className="theia-button secondary" onClick={handleAddBc} disabled={props.surfaces.length === 0}>
                        <i className="codicon codicon-add" />
                        Add Boundary Condition
                    </button>

                    <div className="bc-list">
                        {props.state.boundaryConditions.map((bc) => (
                            <div className="bc-item" key={bc.id}>
                                <span className="bc-type">{bc.type}</span>
                                <span className="bc-surface">{bc.surfaceName}</span>
                                {bc.magnitude !== undefined && <span className="bc-value">{bc.magnitude}</span>}
                                {bc.temperature !== undefined && <span className="bc-value">{bc.temperature} K</span>}
                                <button className="theia-button secondary small" onClick={() => props.onRemoveBc(bc.id)}>
                                    <i className="codicon codicon-trash" />
                                </button>
                            </div>
                        ))}
                    </div>
                </div>

                <div className="fem-section">
                    <div className="fem-section-title">Log</div>
                    <div className="log-viewer">{props.state.logOutput || 'No output yet.'}</div>
                </div>
            </div>
        </div>
    );
}

interface VectorInputProps {
    readonly label: string;
    readonly value: [number, number, number];
    readonly disabled: boolean;
    readonly onChange: (value: [number, number, number]) => void;
}

function VectorInput(props: VectorInputProps): React.ReactElement {
    return (
        <div className="form-row">
            {([0, 1, 2] as const).map((i) => (
                <div className="form-group" key={i}>
                    <label>
                        {props.label} {'XYZ'[i]}
                    </label>
                    <input
                        type="number"
                        step="any"
                        value={props.value[i]}
                        disabled={props.disabled}
                        onChange={(e) => {
                            const next = [...props.value] as [number, number, number];
                            next[i] = parseFloat(e.target.value) || 0;
                            props.onChange(next);
                        }}
                    />
                </div>
            ))}
        </div>
    );
}
