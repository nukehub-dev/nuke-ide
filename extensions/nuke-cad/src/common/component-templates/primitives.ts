/**
 * Primitives component templates: box, cylinder, tube, sphere, cone, and
 * plate-with-hole.
 *
 * Every body is a validated schema-v3 document generated by the GUI build
 * flow driver from `src/browser/document/gui-build-primitives.test.ts`. The
 * bundled JSON under `src/common/samples/` is a generated copy of the
 * canonical `.nuke-cad` fixture, exactly like the pincell sample.
 *
 * Document units are centimetres. Axisymmetric solids are revolved profiles;
 * box and plate-with-hole use a straight sweep so their extrusion height is a
 * sketch-bound parameter (a pad length is numeric-only in the document
 * schema).
 *
 * @module nuke-cad/common
 */

import type { NukeCadDocument } from '../cad-document';
