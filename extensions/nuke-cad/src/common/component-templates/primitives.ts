import type { ComponentTemplate, ComponentTemplateParameter } from './types';

function templateDocument(sample: unknown): NukeCadDocument {
    const document = JSON.parse(JSON.stringify(sample)) as NukeCadDocument;
    document.units = 'cm';
    for (const body of document.bodies) {
        // Template bodies stay presentation-neutral.
        delete body.appearance;
    }
    return document;
}

function lengthParameter(
    name: string,
    label: string,
    defaultValue: number,
    min: number,
    max: number,
    description: string,
    step?: number
): ComponentTemplateParameter {
    return {
        name,
        label,
        kind: 'length',
        unit: 'cm',
        default: defaultValue,
        min,
        max,
        ...(step !== undefined ? { step } : {}),
        description
    };
}

/** Diameter alias over a canonical radius document parameter. */
function diameterAlias(
    name: string,
    label: string,
    defaultValue: number,
    radiusName: string,
    description: string,
    step?: number
): ComponentTemplateParameter {
    return {
        name,
        label,
        kind: 'length',
        unit: 'cm',
        default: defaultValue,
        ...(step !== undefined ? { step } : {}),
        description,
        pair: radiusName,
        derived: { parameter: radiusName, factor: 0.5 }
    };
}

function radiusParameter(
    name: string,
    label: string,
    defaultValue: number,
    min: number,
    max: number,
    description: string,
    step?: number
): ComponentTemplateParameter {
    const diameterName = name === 'radius' ? 'diameter' : name.replace(/Radius$/, 'Diameter');
    return {
        ...lengthParameter(name, label, defaultValue, min, max, description, step),
        pair: diameterName
    };
}

