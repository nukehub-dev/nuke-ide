/**
 * Mechanical component templates: L bracket, flange, stepped shaft, pipe with
 * bore, and bolt-circle plate.
 *
 * Every body is a validated schema-v3 document generated by the GUI build flow
 * driver from `src/browser/document/gui-build-mechanical.test.ts`. The bundled
 * JSON under `src/common/samples/` is a generated copy of the canonical
 * `.nuke-cad` fixture, exactly like the primitive family.
 *
 * Document units are centimetres. Radius is the canonical document parameter
 * wherever the profile is a revolve; diameter parameters are derived aliases
 * with factor 0.5 so the public surface can speak either vocabulary. Hole
 * diameters stay canonical because a circle profile carries a diameter
 * dimension.
 *
 * Circular-pattern counts are numeric-only in the document schema, so the
 * flange and bolt-circle plate ship representative fixed patterns at the
 * default count. The count parameter still drives a construction dimension in
 * the pattern sketch, so overriding it re-solves the sketch and the creation
 * flow accepts the value; the solid keeps the default hole count.
 *
 * @module nuke-cad/common
 */

import type { NukeCadDocument } from '../cad-document';
import boltCirclePlateJson from '../samples/gui_bolt_circle_plate.json';
import flangeJson from '../samples/gui_flange.json';
import lBracketJson from '../samples/gui_l_bracket.json';
import pipeWithBoreJson from '../samples/gui_pipe_with_bore.json';
import steppedShaftJson from '../samples/gui_stepped_shaft.json';
import type { ComponentTemplate, ComponentTemplateParameter } from './types';

function templateDocument(sample: unknown): NukeCadDocument {
    const document = JSON.parse(JSON.stringify(sample)) as NukeCadDocument;
    document.units = 'cm';
    for (const body of document.bodies) {
        // Template bodies stay presentation-neutral.
        delete body.appearance;
    }
    return document;
}

function lengthParameter(
    name: string,
    label: string,
    defaultValue: number,
    min: number,
    max: number,
    description: string,
    step?: number
): ComponentTemplateParameter {
    return {
        name,
        label,
        kind: 'length',
        unit: 'cm',
        default: defaultValue,
        min,
        max,
        ...(step !== undefined ? { step } : {}),
        description
    };
}

/** Radius parameter paired with its derived diameter alias. */
function radiusParameter(
    name: string,
    label: string,
    defaultValue: number,
    min: number,
    max: number,
    description: string,
    step?: number
): ComponentTemplateParameter {
    const diameterName = name === 'radius' ? 'diameter' : name.replace(/Radius$/, 'Diameter');
    return {
        ...lengthParameter(name, label, defaultValue, min, max, description, step),
        pair: diameterName
    };
}

/** Diameter alias over a canonical radius document parameter. */
function diameterAlias(
    name: string,
    label: string,
    defaultValue: number,
    radiusName: string,
    description: string,
    step?: number
): ComponentTemplateParameter {
    return {
        name,
        label,
        kind: 'length',
        unit: 'cm',
        default: defaultValue,
        ...(step !== undefined ? { step } : {}),
        description,
        pair: radiusName,
        derived: { parameter: radiusName, factor: 0.5 }
    };
}

/** Positive-integer count parameter; bounds stay in the declared unit `1`. */
function countParameter(
    name: string,
    label: string,
    defaultValue: number,
    min: number,
    max: number,
    description: string
): ComponentTemplateParameter {
    return {
        name,
        label,
        kind: 'count',
        unit: '1',
        default: defaultValue,
        min,
        max,
        step: 1,
        description
    };
}

