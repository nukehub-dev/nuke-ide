/**
 * Nuclear component templates: the hex cell, control-rod guide tube, and
 * assembly grid plate.
 *
 * Every body is a validated schema-v3 document generated by the GUI build flow
 * driver from `src/browser/document/gui-build-nuclear.test.ts`. The bundled
 * JSON under `src/common/samples/` is a generated copy of the canonical
 * `.nuke-cad` fixture, exactly like the pincell and primitive families.
 *
 * Document units are centimetres. The hex-cell `pitch` is the flat-to-flat
 * distance across the hexagonal cell, which is also the center-to-center
 * spacing of a hex lattice; its profiles are swept along a parameter-driven
 * height path. The guide tube and grid plate follow the primitive convention
 * where a radius is the canonical document parameter and a diameter is a
 * derived alias.
 *
 * The guide tube wall relation is `(outerDiameter - innerDiameter) / 2`, which
 * the resolver cannot express as one multiplicative alias. The sketch carries
 * a construction wall gauge for the `wallThickness` parameter, and
 * `validateGuideTubeWall` checks a resolved triple before a caller builds it.
 *
 * Pattern counts are numeric-only in the document schema, so the grid plate
 * ships a representative 3x3 cell array at the default count. `cellCount`
 * still drives a construction dimension in the plate sketch, so overriding it
 * re-solves the sketch and the creation flow accepts the value; the solid
 * keeps the default cell count.
 *
 * @module nuke-cad/common
 */

import type { NukeCadDocument } from '../cad-document';
import assemblyGridPlateJson from '../samples/gui_assembly_grid_plate.json';
