import hexCellJson from '../samples/gui_hex_cell.json';
import type { ComponentTemplate, ComponentTemplateParameter } from './types';

/** Material tags applied to each template body by label. */
const NUCLEAR_MATERIALS: Readonly<Record<string, Readonly<Record<string, string>>>> = {
    'hex-cell': {
        fuel: 'UO2',
        clad: 'Zircaloy-4',
        moderator: 'H2O'
    },
    'control-rod-guide-tube': {
        'guide-tube': 'Zircaloy-4'
    },
    'assembly-grid-plate': {
        'grid-plate': 'Zircaloy-4'
    }
};

function templateDocument(id: string, sample: unknown): NukeCadDocument {
    const document = JSON.parse(JSON.stringify(sample)) as NukeCadDocument;
    document.units = 'cm';
    const materials = NUCLEAR_MATERIALS[id] ?? {};
    for (const body of document.bodies) {
        // Template bodies stay presentation-neutral and only carry the
        // domain material tag for their labelled region.
        delete body.appearance;
        const material = body.label !== undefined ? materials[body.label] : undefined;
        if (material !== undefined) {
            body.material = material;
        }
    }
    return document;
}

function lengthParameter(
    name: string,
    label: string,
    defaultValue: number,
    min: number,
    max: number,
    description: string,
    step?: number
): ComponentTemplateParameter {
    return {
        name,
        label,
        kind: 'length',
        unit: 'cm',
        default: defaultValue,
        min,
        max,
        ...(step !== undefined ? { step } : {}),
        description
    };
}

/** Radius parameter paired with its derived diameter alias. */
function radiusParameter(
    name: string,
    label: string,
    defaultValue: number,
    min: number,
    max: number,
    description: string,
    step?: number
): ComponentTemplateParameter {
    const diameterName = name === 'radius' ? 'diameter' : name.replace(/Radius$/, 'Diameter');
    return {
        ...lengthParameter(name, label, defaultValue, min, max, description, step),
        pair: diameterName
    };
}

/** Diameter alias over a canonical radius document parameter. */
function diameterAlias(
    name: string,
    label: string,
    defaultValue: number,
    radiusName: string,
    description: string,
    step?: number
): ComponentTemplateParameter {
    return {
        name,
        label,
        kind: 'length',
        unit: 'cm',
        default: defaultValue,
        ...(step !== undefined ? { step } : {}),
        description,
        pair: radiusName,
        derived: { parameter: radiusName, factor: 0.5 }
    };
}

function countParameter(
    name: string,
    label: string,
    defaultValue: number,
    min: number,
    max: number,
    description: string
): ComponentTemplateParameter {
    return {
        name,
        label,
        kind: 'count',
        unit: '1',
        default: defaultValue,
        min,
        max,
        step: 1,
        description
    };
}

/**
 * Check the guide-tube wall relation outside the template resolver.
 *
 * `outerDiameter`, `innerDiameter`, and `wallThickness` describe the same
 * physical wall, so a creation request must not pick three values that
 * disagree. The component-template resolver only supports radius/diameter
 * aliases (a single multiplicative factor), not `(outer - inner) / 2`, so a
 * caller that validates its resolved values can use this helper to reject a
 * conflicting triple before building the document.
 */
export function validateGuideTubeWall(outerDiameter: number, innerDiameter: number, wallThickness: number): string | undefined {
    if (![outerDiameter, innerDiameter, wallThickness].every((value) => Number.isFinite(value))) {
        return 'Guide-tube diameters and wall thickness must be finite numbers';
    }
    if (outerDiameter <= 0 || innerDiameter <= 0 || wallThickness <= 0) {
        return 'Guide-tube diameters and wall thickness must be positive';
    }
    if (innerDiameter >= outerDiameter) {
        return `Guide-tube innerDiameter (${innerDiameter} cm) must be smaller than outerDiameter (${outerDiameter} cm)`;
    }
    const expected = (outerDiameter - innerDiameter) / 2;
    const tolerance = Math.max(Math.abs(expected), Math.abs(wallThickness)) * 1e-9;
    if (Math.abs(expected - wallThickness) > tolerance) {
        return `Guide-tube wallThickness (${wallThickness} cm) must equal (outerDiameter - innerDiameter) / 2 (${expected} cm)`;
    }
    return undefined;
}

